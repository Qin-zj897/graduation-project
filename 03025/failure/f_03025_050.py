N, A, B, C = map(int, input().split())

if A == 100 or B == 100:
  print(N)
else:
  A_1 = N * (A / 100) ** N / (1 - B / 100) + (A / 100) ** N * (C / 100) * (1 - (C / 100) ** (N - 1)) / (1 - B / 100) / (1 - C / 100)
  B_1 = N * (B / 100) ** N / (1 - A / 100) + (B / 100) ** N * (C / 100) * (1 - (C / 100) ** (N - 1))/ (1 - A / 100) / (1 - C / 100)
  A_2 = 2 * N * (A / 100) ** N * (C / 100) ** N / (1 - C / 100) + (A / 100) ** N * (C / 100) ** (N + 1) / (1 - C) ** 2
  B_2 = 2 * N * (B / 100) ** N * (C / 100) ** N / (1 - C / 100) + (B / 100) ** N * (C / 100) ** (N + 1) / (1 - C) ** 2
  
  ans = A_1 + B_1 + A_2 + B_2
  print(ans)